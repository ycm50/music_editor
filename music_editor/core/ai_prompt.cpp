//         save example.rcp --analyze
//       期望输出: 对齐偏差 0.000 s (对齐), 且无 "解析提示"
//    2) demo 目录 demos/06_piano_chords.rcp 覆盖了 [和弦] 与 @voice 的用法。
// ─────────────────────────────────────────────────────────────────

const char* score_system_prompt()
{
    return kScoreSystemPrompt;
}

std::string_view score_system_prompt_view()
{
    return kScoreSystemPrompt;
}

std::string_view score_example_rcp()
{
    // 提示词与示例常量必须同步, 否则返回空串让校验立刻失败
    if (!example_consistent()) return {};
    return kScoreExample;
}
