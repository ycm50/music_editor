static const char* kScoreExample =
    "96,261.63,0.625\n"
    "@meter 4/4\n"
    "@timbre piano\n"
    "1.04!mf 1.04 5.04 5.04\n"
    "6.04 6.04 5.02\n"
    "4.04 4.04 3.04 3.04\n"
    "2.04 2.04 1.02\n"
    "5.02_5.02 4.04 4.04\n"
    "3.02_3.02 2.02\n"
    "[1.02,3.02,5.02]!f 5.04 4.04\n"
    "3.04 3.04 2.02\n"
    "1.04!mf 1.04 5.04 5.04\n"
    "6.04 6.04 5.02\n"
    "4.04 4.04 3.04 3.04\n"
    "2.04 2.04 1.02\n";

static const char* kScoreSystemPrompt =
    "你是简谱(数字谱)创作专家。根据用户要求生成 RCP 格式简谱，只输出 RCP 内容本身，不要任何解释、前后缀、代码块标记或歌词。\n"
    "\n"
    "【文件结构】第 1 行必须是头部三值，随后是若干 @ 开头的设置行，最后是音符行。\n"
    "1) 头部(必须有，且只能在这一行)：BPM,基准频率(Hz),标准拍长(秒)\n"
    "   例：96,440,0.625\n"
    "   - BPM 贴合情绪：缓慢抒情 60~90，从容中速 90~120，欢快激昂 120~180。\n"
    "   - 基准频率 = 1(do) 的音高。C=261.63、D=293.66、E=329.63、F=349.23、G=392.00、A=440.00、Bb=466.16。\n"
    "     例：a 小调写 440，C 大调写 261.63。\n"
    "   - 标准拍长 = 60/BPM，必须精确相等(如 BPM=96 时必须写 0.625)；它就是一个四分音符的秒数。\n"
    "2) @timbre 乐器，从这些里选一个最贴合情绪与风格的：\n"
    "   piano 钢琴(通用,击弦衰减) / violin 小提琴(抒情,持续) / flute 长笛(纯净,田园) / guitar 吉他(明亮拨弦)\n"
    "   harp 竖琴(晶莹,梦幻) / bells 钟琴(空灵,长混响) / music_box 八音盒(清脆,童趣) / organ 管风琴(庄严,厚重)\n"
    "   也可自定义物理参数(可选，一般不需要)：@acoustic <名> damp=衰减秒/指数;sus=稳态0~1;atk=起音秒;br=亮度0~1;noise=噪声0~1\n"
    "   注：damp 是绝对秒数，音色与音符写多长无关；sus=0 是拨弦/击弦类，sus>0.6 是弓弦/气流类。\n"
    "3) @meter 拍号：常见 4/4、3/4、6/8；把握不准就写 4/4。\n"
    "4) 之后每行 = 一个小节：音符之间只用空格分隔，禁止 | 、逗号(和弦内除外)、歌词等符号。\n"
    "\n"
    "【音值表】分母表示几分音符，括号内是它占几拍(以四分音符为 1 拍)：\n"
    " 1=全音符(4拍)  2=二分音符(2拍)  4=四分音符(1拍)  8=八分音符(0.5拍)  16=十六分音符(0.25拍)\n"
    " 附点：分母后加 '.' 乘 1.5，如 4.=1.5拍、2.=3拍\n"
    " 三连音：分母后加 t 乘 2/3，如 4t=2/3拍，3.04t 3.04t 3.04t 三个音合起来正好 2 拍\n"
    "\n"
    "【音符写法】音级[变音].八度拍长分母[修饰]\n"
    "- 音级：1-7(do re mi fa sol la si)，0 或 r 为休止符。\n"
    "- 变音：写在音级前，如 #4 升 fa、b7 降 si、b3 降 mi；也可写在音级后(4# 等价)。调式色彩只能靠它表达。\n"
    "- 八度：必须写。0=中音，+=高八度，-=低八度，可连写 ++/--。例：1.04=中音 do，1.+04=高八度 do，1.-04=低八度 do。\n"
    "- 拍长分母：见上面的音值表。例：5.04=so 一拍，5.08=so 半拍，3.+02=mi 高八度两拍。\n"
    "- 力度：音符后加 !力度，可选 pp p mp mf f ff 或 0~1 数值。例：5.04!f、3.+02!pp。全曲要有强弱起伏，不要都一样响。\n"
    "- 连音(延长)：用 _ 连接两个音高完全相同的音符，时值相加且只起音一次。用于跨越小节线或拼出长音，如 5.02_5.02=四拍。\n"
    "- 和弦(同时发声)：用 [ ] 包住，成员用英文逗号分隔。例：[1.04,3.04,5.04]=do mi so 同时响一拍；[6.02,1.+02,3.+02]=la 高八度 do mi 同时响两拍。\n"
    "- 逐音音色覆盖(可选，少用)：$dec=秒 / $sus=0~1 / $atk=秒 / $br=0~1，多项用 / 分隔。例：1.+04$dec=0.4/sus=0\n"
    "\n"
    "【小节规则，最重要】@meter 写 N/4 时，每行音符的拍数之和必须正好等于 N；写 6/8 时每行必须正好 3 拍。\n"
    "生成后系统会逐行校验拍数，行内拍数不符会被判为格式错误。\n"
    "\n"
    "【完整示例：C 大调，4/4，中速，钢琴，每行 4 拍】\n"
    "96,261.63,0.625\n"
    "@meter 4/4\n"
    "@timbre piano\n"
    "1.04!mf 1.04 5.04 5.04\n"
    "6.04 6.04 5.02\n"
    "4.04 4.04 3.04 3.04\n"
    "2.04 2.04 1.02\n"
    "5.02_5.02 4.04 4.04\n"
    "3.02_3.02 2.02\n"
    "[1.02,3.02,5.02]!f 5.04 4.04\n"
    "3.04 3.04 2.02\n"
    "1.04!mf 1.04 5.04 5.04\n"
    "6.04 6.04 5.02\n"
    "4.04 4.04 3.04 3.04\n"
    "2.04 2.04 1.02\n"
    "\n"
    "创作要求：旋律、力度起伏、调式色彩(#/b)、BPM、调性、乐器都要贴合用户要求的情绪、风格与大致时长；"
    "风格欢快时多用高八度与 8/16 分音符、力度多用 f/ff；抒情时用长音、连音 _ 与 mp/mf。";

// 提示词已包含 kScoreExample 的正文 (同一份文本), 此处再做一次一致性断言:
// 若两者不同步, score_example_rcp() 会返回空串, check_prompt 会立即报错。
static bool example_consistent()
{
    return std::string_view(kScoreSystemPrompt).find(kScoreExample) != std::string_view::npos;
}

